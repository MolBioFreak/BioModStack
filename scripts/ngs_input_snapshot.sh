#!/usr/bin/env bash
# NGS task naming only: retained authority is supplied by the existing receipt
# consumer, not inferred from a read-only upload. Keep legacy snapshot behavior.
ngs_input_snapshot() {
    local source="$1" target="$2" retained="$3" portable="${4:-false}" concrete mode
    concrete="$(readlink -f -- "$source")"
    mode="$(stat -c %a -- "$concrete")"
    if [[ "$retained" == true ]] && (( (8#$mode & 8#222) == 0 )); then
        if [[ "$(stat -c %d -- "$concrete")" == "$(stat -c %d -- "$(dirname -- "$target")")" ]]; then
            ln -- "$concrete" "$target"
        elif [[ "$portable" == true ]]; then
            # A retained result must remain a regular independent name even
            # when its input version lives on another filesystem.
            cp --reflink=auto -- "$concrete" "$target"
            chmod 0444 "$target"
        else
            # A task-local name may reference an already retained version on
            # another filesystem; this is not an independently portable export.
            ln -s -- "$concrete" "$target"
        fi
    else
        cp --reflink=auto -- "$source" "$target"
        chmod 0444 "$target"
    fi
}

# Sidecars belong to the same completed reference publisher. Missing or legacy
# writable indexes are regenerated by the caller in its private task directory.
ngs_reference_index() {
    local source="$1" target="$2" retained="$3" portable="${4:-false}" concrete mode index_mode
    concrete="$(readlink -f -- "$source")"
    [[ "$retained" == true && -f "$concrete.fai" ]] || return 1
    mode="$(stat -c %a -- "$concrete")"
    index_mode="$(stat -c %a -- "$concrete.fai")"
    (( (8#$mode & 8#222) == 0 && (8#$index_mode & 8#222) == 0 )) || return 1
    ngs_input_snapshot "$concrete.fai" "$target.fai" true "$portable"
}

# Called only after FastqDimerAnalysis has joined its native writers.
ngs_finalize_dimer_outputs() {
    local completed
    for completed in dimer_candidates.{fastq,fasta,aligned.bam,aligned.bam.bai,single_ref.aligned.bam,single_ref.aligned.bam.bai} dimer_reference.fasta{,.fai} {dimer,dominant_dimer}_consensus.fasta; do
        if [[ -f "$completed" && ! -L "$completed" ]]; then chmod 0444 "$completed"; fi
    done
}
